// PERF-08: summarise CDP profiles from tools/perf-walk.mjs (--heap-profile 1 / --cpu-profile 1). Pure functions, no I/O.
// Heap: HeapProfiler.stopSampling() -> { head: { callFrame, selfSize, children } } (sampled bytes incl. collected objects when
// started with includeObjectsCollectedByMinorGC/MajorGC). CPU: Profiler.stop() -> { nodes, samples, timeDeltas }.

const shortUrl = (u) => (u ? u.replace(/^https?:\/\/[^/]+\//, '').replace(/\?.*$/, '') : '(native)');
// CDP line numbers are 0-based.
const site = (cf) => `${cf.functionName || '(anonymous)'} ${shortUrl(cf.url)}:${cf.url ? cf.lineNumber + 1 : '-'}`;

// Top allocation sites by self size (function + url:line), with the most common caller chain (up to 3 frames) of each.
export function summariseHeap(profile, topN = 20) {
  const bySite = new Map();
  let total = 0;
  const walk = (node, stack) => {
    const name = site(node.callFrame);
    if (node.selfSize > 0) {
      total += node.selfSize;
      let e = bySite.get(name);
      if (!e) bySite.set(name, (e = { site: name, bytes: 0, callers: new Map() }));
      e.bytes += node.selfSize;
      const chain = stack.slice(-3).reverse().join(' < ') || '(root)';
      e.callers.set(chain, (e.callers.get(chain) || 0) + node.selfSize);
    }
    const next = stack.concat(name);
    for (const c of node.children || []) walk(c, next);
  };
  walk(profile.head, []);
  const rows = [...bySite.values()].sort((a, b) => b.bytes - a.bytes).slice(0, topN).map((e) => {
    const top = [...e.callers.entries()].sort((a, b) => b[1] - a[1])[0];
    return { site: e.site, mb: e.bytes / 1048576, pct: total ? (100 * e.bytes) / total : 0, caller: top ? top[0] : '' };
  });
  return { totalMb: total / 1048576, rows };
}

// Top functions by self time (ms) from a CPU profile.
export function summariseCpu(profile, topN = 20) {
  const dt = new Map(), byId = new Map();
  for (const n of profile.nodes) byId.set(n.id, n);
  for (let i = 0; i < profile.samples.length; i++) dt.set(profile.samples[i], (dt.get(profile.samples[i]) || 0) + (profile.timeDeltas[i] || 0));
  const bySite = new Map();
  let total = 0;
  for (const [id, us] of dt) { const s = site(byId.get(id).callFrame); bySite.set(s, (bySite.get(s) || 0) + us); total += us; }
  const rows = [...bySite.entries()].sort((a, b) => b[1] - a[1]).slice(0, topN).map(([s, us]) => ({ site: s, ms: us / 1000, pct: total ? (100 * us) / total : 0 }));
  return { totalMs: total / 1000, rows };
}

export function renderMd({ title, row, heap, cpu }) {
  const L = [`# ${title}`, '', 'Generated by `node tools/perf-walk.mjs --heap-profile 1` (PERF-08). Sampled allocation profile (interval 32 KB, includes objects collected by minor + major GC), self size per function + url:line; caller = most common 3-frame caller chain.', ''];
  if (row) L.push('Walk row: `' + JSON.stringify({ quality: row.quality, grid: row.grid, frames: row.frames, over16: row.over16, over33: row.over33, itvMax: row.itvMax, p99: row.p99, fps: row.fps, gcSpikes: row.gcSpikes }) + '`', '');
  if (heap) {
    L.push(`## Heap (sampled total ${heap.totalMb.toFixed(0)} MB)`, '', '| # | MB | % | site | top caller chain |', '|---|---|---|---|---|');
    heap.rows.forEach((r, i) => L.push(`| ${i + 1} | ${r.mb.toFixed(1)} | ${r.pct.toFixed(1)} | ${r.site} | ${r.caller} |`));
    L.push('');
  }
  if (cpu) {
    L.push(`## CPU self time (total ${cpu.totalMs.toFixed(0)} ms)`, '', '| # | ms | % | site |', '|---|---|---|---|');
    cpu.rows.forEach((r, i) => L.push(`| ${i + 1} | ${r.ms.toFixed(0)} | ${r.pct.toFixed(1)} | ${r.site} |`));
    L.push('');
  }
  return L.join('\n');
}
