// S8-B2-11: LOD1 preview for the owner (no silent asset changes). For each Quaternius tree (CommonTree/Pine/TwistedTree 1-5) it imports
// the glTF at full detail and at candidate decimations (quadric edge collapse, same importer flags the real import would use),
// into a TEMP folder only - nothing under content/ is touched - and writes design/preview/lod1-trees.data.js, which
// design/preview/lod1-trees.html renders as ASCII at 3 distances with tri counts and a pick box. The owner picks; only then
// QUAT-LOD-01 imports the chosen one (importer `lods`).
// Usage: node tools/mesh-lod-preview.mjs [--ratios 0.35,0.25,0.15] [--out design/preview/lod1-trees.data.js] [name ...]
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readMeshJSON } from './mesh-file.mjs';
import { runCli } from './gltf-import.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const SRC = path.join(root, 'design/meshes/quaternius/glTF');
export const TREE_RE = /^(CommonTree|Pine|TwistedTree)_\d+$/;

/**
 * Triangle soup (3 vertices per triangle, `ranges` in triangles) -> welded, quantised candidate for the page.
 * @param {{pos:number[], triCount:number, ranges:{start:number,count:number,part:string}[]}} json  full mesh json
 * @param {number[]} bbox  [minx,miny,minz,maxx,maxy,maxz] used for the 16-bit quantisation (shared by all candidates of one tree)
 * @param {Record<string,string>} colorOf  material key -> '#rrggbb'
 */
export function encodeCandidate(json, bbox, colorOf) {
  const ext = [0, 1, 2].map((a) => bbox[a + 3] - bbox[a] || 1);
  const q = (v, a) => Math.max(0, Math.min(65535, Math.round(((v - bbox[a]) / ext[a]) * 65535)));
  const map = new Map(); const verts = []; const idx = [];
  for (let i = 0; i < json.triCount * 3; i++) {
    const x = q(json.pos[i * 3], 0), y = q(json.pos[i * 3 + 1], 1), z = q(json.pos[i * 3 + 2], 2);
    const k = `${x},${y},${z}`;
    let id = map.get(k);
    if (id === undefined) { id = verts.length / 3; map.set(k, id); verts.push(x, y, z); }
    idx.push(id);
  }
  const idx32 = verts.length / 3 > 65535;
  const b64 = (ta) => Buffer.from(ta.buffer, ta.byteOffset, ta.byteLength).toString('base64');
  return {
    tris: json.triCount,
    verts: b64(new Uint16Array(verts)),
    idx: b64(idx32 ? new Uint32Array(idx) : new Uint16Array(idx)),
    idx32,
    bbox,
    ranges: json.ranges.map((r) => ({ start: r.start, count: r.count, color: colorOf[r.part.split(':')[1]] || '#888888' })),
  };
}

async function loadPaletteColors() {
  globalThis.ASSETS = globalThis.ASSETS || {};
  await import(new URL('../design/palette.js', import.meta.url).href);
  const P = globalThis.ASSETS.palette;
  const out = {};
  for (const [k, m] of Object.entries(P.materials)) out[k] = P.colors[m.base] || '#888888';
  return out;
}

// Preview-only palette keys per glTF material (the trees have no palette-map texture yet, QUAT-TREES-01 decides the final mats).
// Leaves import as opaque cards here (no --masks), so the tri counts are the cards' geometry, as in the first QUAT-TREES-01 import.
function matsFor(name) {
  const leaf = name.startsWith('Pine') ? 'leaf_dark' : name.startsWith('Twisted') ? 'leaf_light' : 'leaf';
  return { Bark_NormalTree: 'wood', Bark_TwistedTree: 'wood', Leaves_NormalTree: leaf, Leaves_Pine: leaf, Leaves_TwistedTree: leaf };
}

async function importTo(tmp, name, flags) {
  const file = path.join(tmp, `${name}.mesh.json`);
  const matsFile = path.join(tmp, `${name}.mats.json`);
  fs.writeFileSync(matsFile, JSON.stringify(matsFor(name)));
  await runCli([path.join(SRC, `${name}.gltf`), `quaternius/${name}`, '--mats', matsFile, ...flags, '--out', file]);
  return readMeshJSON(file);
}

export async function build({ names, ratios, out }) {
  const colors = await loadPaletteColors();
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'lodprev-'));
  const trees = [];
  try {
    for (const name of names) {
      const full = await importTo(tmp, name, []);
      const bbox = full.bbox.map((v) => Math.round(v * 1e4) / 1e4);
      const cands = [{ label: 'LOD0 full', ratio: 1, ...encodeCandidate(full, bbox, colors) }];
      for (const r of ratios) {
        const target = Math.max(8, Math.round(full.triCount * r));
        const j = await importTo(tmp, `${name}`, ['--simplify', String(target)]);
        cands.push({ label: `LOD1 ${Math.round(r * 100)}%`, ratio: r, ...encodeCandidate(j, bbox, colors) });
      }
      trees.push({ name, height: Math.round((bbox[4] - bbox[1]) * 100) / 100, cands });
      console.log(`${name}: ${cands.map((c) => `${c.label}=${c.tris}`).join('  ')}`);
    }
  } finally { fs.rmSync(tmp, { recursive: true, force: true }); }
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, `// generated by tools/mesh-lod-preview.mjs (S8-B2-11), do not edit\nwindow.LOD1_TREES = ${JSON.stringify(trees)};\n`);
  return trees;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (isMain) {
  const argv = process.argv.slice(2);
  let ratios = [0.35, 0.25, 0.15]; let out = path.join(root, 'design/preview/lod1-trees.data.js'); const rest = [];
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--ratios') ratios = argv[++i].split(',').map(Number);
    else if (argv[i] === '--out') out = path.resolve(argv[++i]);
    else rest.push(argv[i]);
  }
  const all = fs.readdirSync(SRC).filter((f) => f.endsWith('.gltf')).map((f) => f.replace('.gltf', '')).filter((n) => TREE_RE.test(n)).sort();
  const names = rest.length ? rest : all;
  const t0 = Date.now();
  await build({ names, ratios, out });
  console.log(`wrote ${out} (${(fs.statSync(out).size / 1024).toFixed(0)} KB, ${Date.now() - t0} ms); open design/preview/lod1-trees.html`);
}
