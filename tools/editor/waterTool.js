// tools/editor/waterTool.js - ED-WATER-01 (OB-223). Pure controller for editing rect water regions of the world file
// (`water[]`, collection "water"). No DOM/World: the viewport hands in ground points; every edit is one EditRecord
// (commands.js makeFieldEditRecord) handed to `commit(rec)` (main.js: applyEdit + undo stack + world rebuild, which
// rebuilds `world.water` from the doc). Only rect regions are editable; river/circle/generated ones are read-only.
import { makeFieldEditRecord, makeInsertRecord, makeDeleteRecord } from './commands.js';
import { isRiver, applyRiverEdit, normalizeEdit, withDz, withWidth, TERRAIN_NOTE, MIN_HW } from './riverEdits.js'; // ED-WATER-03

export const MIN_SIZE = 1; // metres
export const GENERATED_TIP = 'generated by tools/gen-river-water.mjs';
const r2 = (v) => Math.round(v * 100) / 100;

export function isRect(r) {
  return !!r && (r.shape === undefined || r.shape === 'rect') && Array.isArray(r.rect) && r.rect.length === 4 && r.rect.every(Number.isFinite);
}
export function isCircle(r) {
  return !!r && r.shape === 'circle' && Array.isArray(r.c) && r.c.length === 2 && r.c.every(Number.isFinite) && Number.isFinite(r.r);
}
/** Editable = rect (or no shape) with a 4-number `rect`, or a circle `c` + `r`. */
export function isEditable(r) { return isRect(r) || isCircle(r); }
/** [x0,y0,x1,y1] bounds of an editable region. */
export function boundsOf(r) { return isCircle(r) ? [r.c[0] - r.r, r.c[1] - r.r, r.c[0] + r.r, r.c[1] + r.r] : r.rect; }
/** Camera pose that frames `bounds` filling `fill` (0.6) of the horizontal view at `pitchDeg`. The editor camera at yaw 0 looks toward -y, so it stands on the +y side. */
export function frameCamera(bounds, groundZ, hfovDeg, fill = 0.6, pitchDeg = -35) {
  const [x0, y0, x1, y1] = bounds, cx = (x0 + x1) / 2, cy = (y0 + y1) / 2, ext = Math.max(x1 - x0, y1 - y0, MIN_SIZE);
  const d = ext / fill / (2 * Math.tan(hfovDeg * Math.PI / 360)), p = pitchDeg * Math.PI / 180;
  return { x: cx, y: cy + d * Math.cos(p), z: groundZ - d * Math.sin(p), yawDeg: 0, pitchDeg };
}
/** Plain reason a region is read-only, or '' when editable. */
export function readOnlyReason(r) {
  if (isEditable(r)) return '';
  return r && (r.shape === 'river' || Array.isArray(r.path) || r.shape === 'ribbon') ? GENERATED_TIP : 'not a rectangle or circle (only those can be edited)';
}
export const rectSize = (rect) => ({ w: rect[2] - rect[0], h: rect[3] - rect[1] });

/** Smallest editable region (rect or circle) containing (x,y), or null. Returns the region object. */
export function hitTest(regions, x, y) {
  let best = null, bestA = Infinity;
  for (const r of regions) {
    if (!isEditable(r)) continue;
    const [x0, y0, x1, y1] = boundsOf(r);
    if (x < x0 || x > x1 || y < y0 || y > y1) continue;
    if (isCircle(r) && Math.hypot(x - r.c[0], y - r.c[1]) > r.r) continue;
    const a = isCircle(r) ? Math.PI * r.r * r.r : (x1 - x0) * (y1 - y0);
    if (a < bestA) { best = r; bestA = a; }
  }
  return best;
}

/** 8 handles: corners nw/ne/sw/se and edges n/s/w/e (n = larger y). */
export function handles(rect) {
  const [x0, y0, x1, y1] = rect, mx = (x0 + x1) / 2, my = (y0 + y1) / 2;
  return [
    { id: 'sw', x: x0, y: y0 }, { id: 'se', x: x1, y: y0 }, { id: 'nw', x: x0, y: y1 }, { id: 'ne', x: x1, y: y1 },
    { id: 's', x: mx, y: y0 }, { id: 'n', x: mx, y: y1 }, { id: 'w', x: x0, y: my }, { id: 'e', x: x1, y: my },
  ];
}
/** Circle: one handle 'r' on the east rim. */
export const circleHandles = (r) => [{ id: 'r', x: r.c[0] + r.r, y: r.c[1] }];
/** Region handles (rect: 8, circle: 1). */
export const regionHandles = (r) => (isCircle(r) ? circleHandles(r) : handles(r.rect));
/** Circle radius after dragging the rim handle to (x,y); min 1 m. */
export const resizeRadius = (c, x, y, min = MIN_SIZE) => r2(Math.max(min, Math.hypot(x - c[0], y - c[1])));
/** Nearest handle within `tol` metres (corners win ties), or null. */
export function hitHandle(rect, x, y, tol = 1.5) {
  let best = null, bd = tol;
  for (const h of handles(rect)) { const d = Math.hypot(h.x - x, h.y - y); if (d <= bd) { best = h; bd = d; } }
  return best ? best.id : null;
}

/** Drag handle `id` to (x,y): moves only that edge(s); each side keeps >= `min` metres. Returns a new rect. */
export function resizeRect(rect, id, x, y, min = MIN_SIZE) {
  let [x0, y0, x1, y1] = rect;
  if (id.includes('w')) x0 = Math.min(x, x1 - min);
  if (id.includes('e')) x1 = Math.max(x, x0 + min);
  if (id.includes('s')) y0 = Math.min(y, y1 - min);
  if (id.includes('n')) y1 = Math.max(y, y0 + min);
  return [r2(x0), r2(y0), r2(x1), r2(y1)];
}
/** Translate by (dx,dy). */
export function moveRect(rect, dx, dy) { return [r2(rect[0] + dx), r2(rect[1] + dy), r2(rect[2] + dx), r2(rect[3] + dy)]; }
/** Set width/height in metres keeping the min corner fixed; below min clamps to MIN_SIZE. null keeps a side. */
export function setRectSize(rect, w, h, min = MIN_SIZE) {
  const [x0, y0, x1, y1] = rect;
  return [x0, y0, r2(x0 + (w == null ? x1 - x0 : Math.max(min, w))), r2(y0 + (h == null ? y1 - y0 : Math.max(min, h)))];
}

/** Max water depth over a region: surface z minus the lowest floor sample on a `step` m grid (incl. edges). null when unknown. */
export function maxDepth(r, floorAt, step = 1) {
  if (!isEditable(r) || typeof floorAt !== 'function' || !Number.isFinite(r.z)) return null;
  const [x0, y0, x1, y1] = boundsOf(r); let low = Infinity;
  const nx = Math.max(1, Math.ceil((x1 - x0) / step)), ny = Math.max(1, Math.ceil((y1 - y0) / step));
  for (let i = 0; i <= nx; i++) for (let j = 0; j <= ny; j++) {
    const x = x0 + (x1 - x0) * i / nx, y = y0 + (y1 - y0) * j / ny;
    if (isCircle(r) && Math.hypot(x - r.c[0], y - r.c[1]) > r.r) continue;
    const f = floorAt(x, y); if (Number.isFinite(f) && f > -1e6 && f < low) low = f;
  }
  return low === Infinity ? null : r2(r.z - low);
}
/** Fresh region for "New pool": 6x6 m rect or r 3 m circle centred on (x,y), surface = floor + 0.4. */
export function makePool(shape, x, y, floorZ, id) {
  const base = { id, look: 'pond', z: r2(floorZ + 0.4) };
  return shape === 'circle' ? { ...base, shape: 'circle', c: [r2(x), r2(y)], r: 3 } : { ...base, shape: 'rect', rect: [r2(x - 3), r2(y - 3), r2(x + 3), r2(y + 3)] };
}

/**
 * @param {{doc:Object, fileId:string, commit:(rec:Object)=>void, onChange?:()=>void}} o
 * `doc.files.get(fileId).def.water` is the live list; edits go through `commit` only.
 */
export function createWaterTool({ doc, fileId, commit, onChange = () => {}, floorAt = null }) {
  const list = () => doc.files.get(fileId).def.water || [];
  const st = { pt: -1, sel: null, armed: null, drag: null /* { mode:'move'|handle id, x, y, start:rect } */, preview: null, msg: '' };
  const find = (id) => { const i = list().findIndex((r) => r.id === id); return i < 0 ? null : { r: list()[i], i }; };
  const edit = (id, patch, label) => {
    const f = find(id); if (!f || !isEditable(f.r)) return false;
    if (Object.keys(patch).every((k) => JSON.stringify(f.r[k]) === JSON.stringify(patch[k]))) return false;
    commit(makeFieldEditRecord(label, fileId, 'water', f.r, f.i, patch)); onChange(); return true;
  };
  const edits = () => doc.files.get(fileId).def.riverEdits || [];
  const riverEdit = (id) => { const e = edits().find((x) => x.id === id); return e ? normalizeEdit(e) : null; };
  /** One undo step: the riverEdits[] item + the ribbon region (path / riverApplied) change together (batch record). */
  function riverCommit(next, label) {
    const f = find(st.sel); if (!f || !isRiver(f.r)) return false;
    const prev = riverEdit(st.sel), region = applyRiverEdit(f.r, next);
    if (JSON.stringify(prev) === JSON.stringify(next) && JSON.stringify(region.path) === JSON.stringify(f.r.path)) return false;
    const list = edits(), j = list.findIndex((x) => x.id === st.sel), batch = [];
    const item = next && { id: st.sel, ...(next.dz ? { dz: next.dz } : {}), ...(Object.keys(next.hw).length ? { hw: { ...next.hw } } : {}) };
    if (!next && j >= 0) batch.push(makeDeleteRecord(fileId, 'riverEdits', list[j], j));
    else if (next && j < 0) batch.push(makeInsertRecord(fileId, 'riverEdits', item));
    else if (next) batch.push(makeFieldEditRecord(label, fileId, 'riverEdits', list[j], j, { dz: undefined, hw: undefined, ...item }));
    batch.push(makeFieldEditRecord(label, fileId, 'water', f.r, f.i, { path: region.path, riverApplied: region.riverApplied }));
    commit({ label, batch }); onChange(); return true;
  }
  const api = {
    st,
    regions: () => list().map((r) => ({ id: r.id, editable: isEditable(r), tip: readOnlyReason(r), look: r.look, z: r.z, ...(isRect(r) ? rectSize(r.rect) : {}), ...(isCircle(r) ? { circle: true, radius: r.r } : {}) })),
    bounds(id = st.sel) { const f = id && find(id); return f && isEditable(f.r) ? boundsOf(f.r) : null; },
    select(id) { const f = id && find(id); st.sel = f ? id : null; st.armed = null; st.msg = f && !isRiver(f.r) ? readOnlyReason(f.r) : ''; st.pt = -1; st.drag = st.preview = null; onChange(); return !!f; },
    /** Click at a ground point: picks the smallest rect containing it (null = none). */
    pick(x, y) { const r = hitTest(list(), x, y); api.select(r ? r.id : null); return r ? r.id : null; },
    current() { const f = st.sel && find(st.sel); return f ? f.r : null; },
    /** Press: on a handle of the selected rect -> resize, inside it -> move; else false. */
    down(x, y) {
      const r = api.current(); if (isRiver(r)) return api.pickPoint(x, y) >= 0; // ED-WATER-03: click a centre-line point
      if (!r || !isEditable(r)) return false;
      if (isCircle(r)) {
        const h = Math.hypot(x - (r.c[0] + r.r), y - r.c[1]) <= 1.5 ? 'r' : null;
        if (!h && Math.hypot(x - r.c[0], y - r.c[1]) > r.r) return false;
        st.drag = { mode: h || 'move', x, y, start: { c: r.c.slice(), r: r.r } }; st.preview = { c: r.c.slice(), r: r.r }; return true;
      }
      const h = hitHandle(r.rect, x, y);
      const inside = x >= r.rect[0] && x <= r.rect[2] && y >= r.rect[1] && y <= r.rect[3];
      if (!h && !inside) return false;
      st.drag = { mode: h || 'move', x, y, start: r.rect.slice() }; st.preview = r.rect.slice(); return true;
    },
    move(x, y) {
      const d = st.drag; if (!d) return;
      if (!Array.isArray(d.start)) { st.preview = d.mode === 'move' ? { c: [r2(d.start.c[0] + x - d.x), r2(d.start.c[1] + y - d.y)], r: d.start.r } : { c: d.start.c.slice(), r: resizeRadius(d.start.c, x, y) }; onChange(); return; }
      st.preview = d.mode === 'move' ? moveRect(d.start, x - d.x, y - d.y) : resizeRect(d.start, d.mode, x, y);
      onChange();
    },
    /** Release: ONE undo step (nothing when the rect did not change). */
    up() {
      const d = st.drag, rect = st.preview; st.drag = st.preview = null;
      if (!d || !rect) return false;
      if (!Array.isArray(rect)) return edit(st.sel, { c: rect.c, r: rect.r }, d.mode === 'move' ? 'move water' : 'resize water');
      return edit(st.sel, { rect }, d.mode === 'move' ? 'move water' : 'resize water');
    },
    /** "New pool" at ground point (x,y): one undo step, selected at once. Returns the id or ''. */
    createPool(x, y, shape = 'rect') {
      const fz = floorAt ? floorAt(x, y) : NaN; if (!Number.isFinite(x) || !Number.isFinite(y) || !Number.isFinite(fz) || fz <= -1e6) { st.msg = 'no ground under the view centre'; onChange(); return ''; }
      let n = list().length + 1; while (find('pond_' + n)) n++;
      const reg = makePool(shape, x, y, fz, 'pond_' + n);
      const doc0 = doc.files.get(fileId).def; if (!doc0.water) doc0.water = [];
      commit(makeInsertRecord(fileId, 'water', reg)); api.select(reg.id); return reg.id;
    },
    /** Delete the selected editable region; needs a second call ("Delete? click again") while armed. */
    deleteSelected(confirm = true) {
      const f = st.sel && find(st.sel); if (!f || !isEditable(f.r)) return false;
      if (confirm && st.armed !== st.sel) { st.armed = st.sel; onChange(); return false; }
      st.armed = null; const rec = makeDeleteRecord(fileId, 'water', f.r, f.i); st.sel = null; st.drag = st.preview = null; st.msg = '';
      commit(rec); onChange(); return true;
    },
    // ---- ED-WATER-03: river ribbon surface edits (z offset of the whole ribbon, per-point half width). Terrain banks are NOT touched.
    isRiverSel() { const c = api.current(); return isRiver(c); },
    riverInfo(id = st.sel) {
      const f = id && find(id); if (!f || !isRiver(f.r)) return null;
      const e = riverEdit(id), ap = f.r.riverApplied || {};
      return { id, note: TERRAIN_NOTE, dz: e ? e.dz : 0, edit: e, pt: st.pt, points: f.r.path.map((p, i) => ({ i, x: p[0], y: p[1], z: p[2], hw: p[3], hw0: ap.hw && ap.hw[i] != null ? ap.hw[i] : p[3] })) };
    },
    /** Select the river point nearest (x,y) within tol m (-1 = none). */
    pickPoint(x, y, tol = 6) {
      const c = api.current(); if (!isRiver(c)) return -1;
      let b = -1, bd = tol; c.path.forEach((p, i) => { const d = Math.hypot(p[0] - x, p[1] - y); if (d <= bd) { b = i; bd = d; } });
      st.pt = b; onChange(); return b;
    },
    /** Set the whole-ribbon surface z offset (m, absolute vs the generated base). One undo step. */
    setRiverDz(dz) { return Number.isFinite(dz) && riverCommit(withDz(riverEdit(st.sel), dz), 'river level'); },
    /** Set point i's half width (m); equal to the base value removes the override. One undo step. */
    setRiverWidth(i, hw) {
      const info = api.riverInfo(); if (!info || !info.points[i] || !Number.isFinite(hw)) return false;
      return riverCommit(withWidth(info.edit, i, Math.max(MIN_HW, hw), info.points[i].hw0), 'river width');
    },
    looks() { return [...new Set(list().map((r) => r.look).filter((l) => typeof l === 'string' && l))]; },
    setLook(look) { return typeof look === 'string' && !!look && edit(st.sel, { look }, 'water look'); },
    depth(id = st.sel) { const f = id && find(id); return f ? maxDepth(f.r, floorAt) : null; },
    setSurfaceZ(z) { return Number.isFinite(z) && edit(st.sel, { z: r2(z) }, 'water level'); },
    setRadius(r) { const c = api.current(); return !!c && isCircle(c) && Number.isFinite(r) && edit(st.sel, { r: r2(Math.max(MIN_SIZE, r)) }, 'resize water'); },
    setSize(w, h) { const r = api.current(); return !!r && isRect(r) && edit(st.sel, { rect: setRectSize(r.rect, w, h) }, 'resize water'); },
  };
  return api;
}
