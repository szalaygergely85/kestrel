// tools/editor/waterTool.js - ED-WATER-01 (OB-223). Pure controller for editing rect water regions of the world file
// (`water[]`, collection "water"). No DOM/World: the viewport hands in ground points; every edit is one EditRecord
// (commands.js makeFieldEditRecord) handed to `commit(rec)` (main.js: applyEdit + undo stack + world rebuild, which
// rebuilds `world.water` from the doc). Only rect regions are editable; river/circle/generated ones are read-only.
import { makeFieldEditRecord } from './commands.js';

export const MIN_SIZE = 1; // metres
export const GENERATED_TIP = 'generated by tools/gen-river-water.mjs';
const r2 = (v) => Math.round(v * 100) / 100;

/** Editable = rect shape (or no shape) with a 4-number `rect`. */
export function isEditable(r) {
  return !!r && (r.shape === undefined || r.shape === 'rect') && Array.isArray(r.rect) && r.rect.length === 4 && r.rect.every(Number.isFinite);
}
/** Plain reason a region is read-only, or '' when editable. */
export function readOnlyReason(r) {
  if (isEditable(r)) return '';
  return r && (r.shape === 'river' || Array.isArray(r.path) || r.shape === 'ribbon') ? GENERATED_TIP : 'not a rectangle (only rect water can be edited)';
}
export const rectSize = (rect) => ({ w: rect[2] - rect[0], h: rect[3] - rect[1] });

/** Smallest editable rect containing (x,y), or null. Returns the region object. */
export function hitTest(regions, x, y) {
  let best = null, bestA = Infinity;
  for (const r of regions) {
    if (!isEditable(r)) continue;
    const [x0, y0, x1, y1] = r.rect;
    if (x < x0 || x > x1 || y < y0 || y > y1) continue;
    const a = (x1 - x0) * (y1 - y0);
    if (a < bestA) { best = r; bestA = a; }
  }
  return best;
}

/** 8 handles: corners nw/ne/sw/se and edges n/s/w/e (n = larger y). */
export function handles(rect) {
  const [x0, y0, x1, y1] = rect, mx = (x0 + x1) / 2, my = (y0 + y1) / 2;
  return [
    { id: 'sw', x: x0, y: y0 }, { id: 'se', x: x1, y: y0 }, { id: 'nw', x: x0, y: y1 }, { id: 'ne', x: x1, y: y1 },
    { id: 's', x: mx, y: y0 }, { id: 'n', x: mx, y: y1 }, { id: 'w', x: x0, y: my }, { id: 'e', x: x1, y: my },
  ];
}
/** Nearest handle within `tol` metres (corners win ties), or null. */
export function hitHandle(rect, x, y, tol = 1.5) {
  let best = null, bd = tol;
  for (const h of handles(rect)) { const d = Math.hypot(h.x - x, h.y - y); if (d <= bd) { best = h; bd = d; } }
  return best ? best.id : null;
}

/** Drag handle `id` to (x,y): moves only that edge(s); each side keeps >= `min` metres. Returns a new rect. */
export function resizeRect(rect, id, x, y, min = MIN_SIZE) {
  let [x0, y0, x1, y1] = rect;
  if (id.includes('w')) x0 = Math.min(x, x1 - min);
  if (id.includes('e')) x1 = Math.max(x, x0 + min);
  if (id.includes('s')) y0 = Math.min(y, y1 - min);
  if (id.includes('n')) y1 = Math.max(y, y0 + min);
  return [r2(x0), r2(y0), r2(x1), r2(y1)];
}
/** Translate by (dx,dy). */
export function moveRect(rect, dx, dy) { return [r2(rect[0] + dx), r2(rect[1] + dy), r2(rect[2] + dx), r2(rect[3] + dy)]; }
/** Set width/height in metres keeping the min corner fixed; below min clamps to MIN_SIZE. null keeps a side. */
export function setRectSize(rect, w, h, min = MIN_SIZE) {
  const [x0, y0, x1, y1] = rect;
  return [x0, y0, r2(x0 + (w == null ? x1 - x0 : Math.max(min, w))), r2(y0 + (h == null ? y1 - y0 : Math.max(min, h)))];
}

/**
 * @param {{doc:Object, fileId:string, commit:(rec:Object)=>void, onChange?:()=>void}} o
 * `doc.files.get(fileId).def.water` is the live list; edits go through `commit` only.
 */
export function createWaterTool({ doc, fileId, commit, onChange = () => {} }) {
  const list = () => doc.files.get(fileId).def.water || [];
  const st = { sel: null, drag: null /* { mode:'move'|handle id, x, y, start:rect } */, preview: null, msg: '' };
  const find = (id) => { const i = list().findIndex((r) => r.id === id); return i < 0 ? null : { r: list()[i], i }; };
  const edit = (id, patch, label) => {
    const f = find(id); if (!f || !isEditable(f.r)) return false;
    if (Object.keys(patch).every((k) => JSON.stringify(f.r[k]) === JSON.stringify(patch[k]))) return false;
    commit(makeFieldEditRecord(label, fileId, 'water', f.r, f.i, patch)); onChange(); return true;
  };
  const api = {
    st,
    regions: () => list().map((r) => ({ id: r.id, editable: isEditable(r), tip: readOnlyReason(r), look: r.look, z: r.z, ...(isEditable(r) ? rectSize(r.rect) : {}) })),
    select(id) { const f = id && find(id); st.sel = f ? id : null; st.msg = f ? readOnlyReason(f.r) : ''; st.drag = st.preview = null; onChange(); return !!f; },
    /** Click at a ground point: picks the smallest rect containing it (null = none). */
    pick(x, y) { const r = hitTest(list(), x, y); api.select(r ? r.id : null); return r ? r.id : null; },
    current() { const f = st.sel && find(st.sel); return f ? f.r : null; },
    /** Press: on a handle of the selected rect -> resize, inside it -> move; else false. */
    down(x, y) {
      const r = api.current(); if (!r || !isEditable(r)) return false;
      const h = hitHandle(r.rect, x, y);
      const inside = x >= r.rect[0] && x <= r.rect[2] && y >= r.rect[1] && y <= r.rect[3];
      if (!h && !inside) return false;
      st.drag = { mode: h || 'move', x, y, start: r.rect.slice() }; st.preview = r.rect.slice(); return true;
    },
    move(x, y) {
      const d = st.drag; if (!d) return;
      st.preview = d.mode === 'move' ? moveRect(d.start, x - d.x, y - d.y) : resizeRect(d.start, d.mode, x, y);
      onChange();
    },
    /** Release: ONE undo step (nothing when the rect did not change). */
    up() {
      const d = st.drag, rect = st.preview; st.drag = st.preview = null;
      if (!d || !rect) return false;
      return edit(st.sel, { rect }, d.mode === 'move' ? 'move water' : 'resize water');
    },
    setSurfaceZ(z) { return Number.isFinite(z) && edit(st.sel, { z: r2(z) }, 'water level'); },
    setSize(w, h) { const r = api.current(); return !!r && isEditable(r) && edit(st.sel, { rect: setRectSize(r.rect, w, h) }, 'resize water'); },
  };
  return api;
}
