// UNDER-02 / OB-191 (arch 38.75): builds content/levels/crypt.level.json (stair + 3 rooms, keepTerrain, nav floors) and patches
// world_m1 (structure `crypt`, dressing meshes cryptBrick*/cryptCoffin/cryptBanner, anchors, state flags). Re-runnable.
//   node tools/gen-crypt.mjs
import fs from 'node:fs';
import { stringifyContent } from '../engine/index.js';
import { loadM1 } from '../game/js/quest/under/loadM1.mjs';

const OX = 1650, OY = 1346, OZ = -60, W = 31, H = 32, ST = [26, 27], DOOR_Z = -50.5, STEP = 0.33;
const FLOOR = 3.2, CEIL = 5.8, TOP = 6.1; // rooms: world floor -56.8
const r2 = (v) => Math.round(v * 100) / 100;
const { groundAt } = await loadM1('mesh');
const g = (c, r) => groundAt(OX + c + 0.5, OY + r + 0.5);

const rows = Array.from({ length: H }, (_, r) => Array.from({ length: W }, (_, c) => (r <= 1 || r >= H - 1 || c === 0 || c >= W - 2 ? ',' : '#')));
const legend = {
  ',': { ceilH: 'sky', ceilMat: 'sky', desc: 'ground reference ring: terrain, not carved', floorH: 9.5, floorMat: 'grass', solid: false, terrainFloor: true, wallMat: 'stone', zone: 'outside' },
  '#': { ceilH: CEIL, topH: TOP, ceilMat: 'stone', floorH: TOP, floorMat: 'floor', wallMat: 'stone', solid: true, keepTerrain: true, desc: 'crypt wall / fill' },
  '.': { ceilH: CEIL, topH: TOP, ceilMat: 'stone', floorH: FLOOR, floorMat: 'floor', wallMat: 'stone', solid: false, keepTerrain: true, desc: 'crypt floor', zone: 'crypt' },
};
const pool = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789@$%&*+=~^:;<>?'.split('');
const put = (c, r, ch) => { rows[r][c] = ch; };
// rooms: interior c21..27, rows 3..9 / 13..19 / 23..29; rings are the '#' fill; interiors + corridors + door cell are floor
for (const r0 of [3, 13, 23]) for (let r = r0; r < r0 + 7; r++) for (let c = 21; c <= 27; c++) put(c, r, '.');
for (const r of [10, 11, 12, 20, 21, 22]) for (const c of [24, 25]) put(c, r, '.');
for (const r of ST) put(20, r, '.'); // doorway cell into room 1 (floor = room floor)
// stair c=1..19 (k = c-1): trench (carved, open sky) until the terrain clears the tunnel roof, then covered
let covered = false, coverC = -1;
for (let c = 1; c <= 19; c++) {
  const k = c - 1, fl = r2(DOOR_Z - OZ - STEP * k);
  const gr = Math.min(g(c, 25), g(c, 26), g(c, 27), g(c, 28));
  if (!covered && gr >= fl + 2.4 + OZ + 0.45) { covered = true; coverC = c; }
  const s = pool.shift(), f = pool.shift();
  if (!covered) {
    legend[s] = { ceilH: 'sky', ceilMat: 'sky', floorH: fl, floorMat: 'floor', wallMat: 'stone', solid: false, desc: `crypt stair ${k} (open trench, carved)`, zone: 'crypt' };
    legend[f] = { ceilH: 'sky', ceilMat: 'sky', floorH: r2(gr + 0.4 - OZ), floorMat: 'floor', wallMat: 'stone', solid: true, desc: `trench wall ${k} (top 0.4 m over the rim)` };
  } else {
    legend[s] = { ceilH: r2(fl + 2.2), topH: r2(fl + 2.4), ceilMat: 'stone', floorH: fl, floorMat: 'floor', wallMat: 'stone', solid: false, keepTerrain: true, desc: `crypt stair ${k} (covered)`, zone: 'crypt' };
    legend[f] = { ceilH: r2(fl + 2.2), topH: r2(fl + 2.4), ceilMat: 'stone', floorH: r2(fl + 2.4), floorMat: 'floor', wallMat: 'stone', solid: true, keepTerrain: true, desc: `tunnel wall ${k}` };
  }
  for (const r of ST) put(c, r, s);
  put(c, 25, f); put(c, 28, f);
}
const lt = (id, c, r, z) => ({ id, on: true, preset: 'torch', x: c + 0.5, y: r + 0.5, z });
const lights = [];
for (const [n, r0] of [[1, 23], [2, 13], [3, 3]]) { lights.push(lt(`torch${n}a`, 21, r0, FLOOR + 1.6), lt(`torch${n}b`, 27, r0 + 6, FLOOR + 1.6)); }
lights.push(lt('torchStair', 17, 26, r2(DOOR_Z - OZ - STEP * 16 + 1.5)));
const level = {
  kind: 'level', schema: 1, id: 'crypt', nextId: 1, name: 'crypt', title: 'The Cemetery Crypt', version: 1, cellSize: 1, ambience: 'crypt',
  note: 'UNDER-02 / OB-191 (arch 38.75): generated by tools/gen-crypt.mjs. Placed at (1650,1346,-60). Stair from the cemetery crypt door (world 1650.9,1373) east and down (open carved trench, then a covered tunnel), 3 rooms of 7x7 m (floor -56.8) joined by 2-wide corridors, rooms stacked north. All cells keepTerrain except the trench. Mesh physics only.',
  size: { w: W, h: H }, rows: rows.map((r) => r.join('')), legend,
  start: { x: 1.5, y: 27, facingDeg: 0, pitchDeg: 0, eyeH: 1.6, pose: 'standing' },
  ambient: { preset: 'ambient' }, lights, props: [], interactables: [], triggers: [], markers: [], layers: {},
};
fs.writeFileSync('content/levels/crypt.level.json', JSON.stringify(level, null, 2) + '\n', 'utf8');

const FILE = 'content/worlds/world_m1.world.json', d = JSON.parse(fs.readFileSync(FILE, 'utf8'));
const mine = (id) => /^crypt[A-Z]|^chestCrypt$|^crypt$/.test(id);
d.structures = d.structures.filter((s) => !mine(s.id)); d.entities = d.entities.filter((e) => !mine(e.id));
const fi = d.structures.findIndex((s) => s.id === 'fordCellar');
d.structures.splice(fi + 1, 0, { id: 'crypt', level: 'crypt', note: 'UNDER-02 / OB-191: cemetery crypt under the facade (cem31..36); level (0,0) -> world (1650,1346); stair rows y 1372..1374, rooms floor -56.8; keepTerrain, mesh physics', origin: { x: OX, y: OY, z: OZ }, yawSteps: 0 });
const FZ = OZ + FLOOR, mesh = (id, m, x, y, z, yaw, sc) => d.structures.push({ id, mesh: 'quaternius/' + m, origin: { x, y, z }, ...(sc ? { scale: sc } : {}), yawDeg: yaw });
mesh('cryptBrick1', 'Prop_Brick1', 1672.2, 1374.6, FZ, 20); mesh('cryptBrick2', 'Prop_Brick3', 1677.0, 1370.8, FZ, 150, 0.9);
mesh('cryptBrick3', 'Prop_Brick2', 1672.0, 1364.8, FZ, 70); mesh('cryptBrick4', 'Prop_Brick4', 1677.0, 1356.0, FZ, 200);
mesh('cryptCoffin', 'Prop_Crate', 1674.4, 1360.6, FZ, 0, 1.3); // coffin stand-in (designer may swap)
mesh('cryptBanner', 'Prop_Vine5', 1671.15, 1352.5, FZ + 1.2, 90, 1); // banner stand-in on the room 3 west wall
const prop = (id, x, y, z, note, comp, yawDeg) => d.entities.push({ id, type: 'prop', x, y, z, ...(yawDeg !== undefined ? { yawDeg } : {}), ...(comp ? { components: comp } : {}), note });
const ins = (t) => ({ inspect: { text: t } });
prop('cryptNames', 1676.7, 1371.3, FZ, 'UNDER-02: scraped names on the room 1 east wall (inspect)', ins('note.crypt.walls'));
prop('cryptCoffin', 1674.4, 1360.6, FZ, 'UNDER-02: pushed-open coffin, room 2 (inspect)', ins('note.crypt.coffin'));
prop('cryptBanner', 1671.4, 1352.5, FZ + 0.6, 'UNDER-02: rotted banner, room 3 (inspect)', ins('note.crypt.banner'));
prop('chestCrypt', 1674.5, 1349.7, FZ, 'UNDER-02: the earned chest in room 3 (opens after its skeletons are dead; chestDefs.js table)', { voxel: { anim: 'closed', loop: false, model: 'chestBig' }, ...ins('note.crypt.chest') }, 180);
Object.assign(d.state, { 'under.crypt.doorOpen': false, 'under.crypt.chest.chestCrypt': false, 'under.crypt.cleared': false });
fs.writeFileSync(FILE, stringifyContent(d), 'utf8');

const man = JSON.parse(fs.readFileSync('content/manifest.json', 'utf8'));
if (!man.files.includes('levels/crypt.level.json')) { man.files.splice(man.files.indexOf('levels/ford_cellar.level.json') + 1, 0, 'levels/crypt.level.json'); fs.writeFileSync('content/manifest.json', JSON.stringify(man, null, 2) + '\n', 'utf8'); }
console.log('crypt level written; trench k<' + (coverC - 1) + ', covered from c=' + coverC + ', lights', lights.length);
